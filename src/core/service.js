// Колоноскопия и гастроскопия идут в одних и тех же данных: одна анкета
// на клинику, один врач с тезисами про обе процедуры. Пациенту, который
// пришёл за колоноскопией, аргумент «выполняет 2000 гастроскопий в год»
// не говорит ничего — он про другое исследование.
//
// Здесь одно место, где записано, что считать «чужой процедурой».
// Им пользуются и анкета клиники, и сборка сообщения.

const OTHER_PROCEDURE = {
  colono: /эгдс|гастроскоп/i,
  gastro: /колоноскоп|фкс/i,
}

/** Текст говорит про другую процедуру, не про выбранную услугу? */
export function isAboutOtherProcedure(text, serviceId) {
  const foreign = OTHER_PROCEDURE[serviceId]
  return Boolean(foreign && foreign.test(text ?? ''))
}
